JSEQ_A = "JSEQ-A"
MFC_DI_A = "MFC-DI-A"
METHODS = (JSEQ_A, MFC_DI_A)
EPS = 1e-8


def _softmax(values: np.ndarray, axis: int = -1) -> np.ndarray:
    shifted = values - np.max(values, axis=axis, keepdims=True)
    exp = np.exp(np.clip(shifted, -60.0, 60.0))
    return exp / np.maximum(exp.sum(axis=axis, keepdims=True), EPS)


class JSEQPolicy:
    """Delayed-queue estimator plus MEC completion-cost routing.

    The estimator uses only the broadcast state and arrivals generated by this
    policy since that state.  The current physical queue is deliberately not
    accessed.  A low-temperature softmax avoids undefined deterministic tie
    breaking when all users receive the same delayed summary.
    """

    def __init__(self, env: JointMAPPOEdgeEnv, temperature: float) -> None:
        self.env = env
        self.temperature = max(float(temperature), 1e-4)
        self.arrival_history: deque[tuple[int, np.ndarray]] = deque(
            maxlen=max(1, env.feedback_delay + env.broadcast_period + 2)
        )

    def _estimated_queue_mb(self) -> np.ndarray:
        feedback = self.env.feedback_buffer.get(self.env.feedback_delay)
        capacities = self.env.edge_capacities_mb_s.astype(np.float64)
        estimate = feedback.wait_s.astype(np.float64) * capacities
        # The timestamp belongs to the selected buffer element.  Using the
        # environment's latest broadcast timestamp is incorrect whenever the
        # delayed entry was generated by an earlier periodic broadcast.
        source_slot = int(feedback.source_slot)
        current_slot = int(self.env.slot_index)
        history = [
            arrivals
            for slot, arrivals in self.arrival_history
            if source_slot <= int(slot) < current_slot
        ]
        for arrivals in history:
            estimate = np.maximum(
                0.0,
                estimate - capacities * self.env.cfg.slot_s + arrivals,
            )
        return estimate

    def portfolios(self) -> np.ndarray:
        queue_mb = self._estimated_queue_mb()
        capacities = self.env.edge_capacities_mb_s.astype(np.float64)
        wait_s = queue_mb / np.maximum(capacities, EPS)
        service_s = self.env.cfg.task_compute_mb / np.maximum(capacities, EPS)
        locations = self.env._locations()  # current local information
        costs = np.empty((self.env.cfg.n_users, self.env.cfg.n_edges), dtype=np.float64)
        for user, loc in enumerate(locations):
            communication = np.asarray(
                [self.env._transmission_delay_s(loc, edge) for edge in range(self.env.cfg.n_edges)],
                dtype=np.float64,
            )
            costs[user] = communication + service_s + wait_s
        scale = np.maximum(np.std(costs, axis=1, keepdims=True), 1e-3)
        return _softmax(-costs / (self.temperature * scale), axis=1).astype(np.float32)

    def observe(self, result: SlotResult) -> None:
        # JSEQ observes admission acknowledgements for tasks dispatched by the
        # controller.  Hidden background work is deliberately excluded.
        task_accepted = (
            result.task_accepted_load_mb
            if result.task_accepted_load_mb is not None
            else result.server_arrival_load_mb
        )
        self.arrival_history.append(
            (int(result.slot_index), np.asarray(task_accepted, dtype=np.float64).copy())
        )


class MFCActor(nn.Module):
    def __init__(self, input_dim: int, d: int, hidden: int) -> None:
        super().__init__()
        self.body = nn.Sequential(
            nn.Linear(input_dim, hidden),
            nn.Tanh(),
            nn.Linear(hidden, hidden),
            nn.Tanh(),
            nn.Linear(hidden, d),
        )
        self.log_std = nn.Parameter(torch.full((d,), -0.7))

    def distribution(self, features: torch.Tensor) -> Normal:
        mean = self.body(features)
        std = self.log_std.clamp(-2.5, 0.5).exp().expand_as(mean)
        return Normal(mean, std)


class MFCCritic(nn.Module):
    def __init__(self, input_dim: int, hidden: int) -> None:
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, hidden),
            nn.Tanh(),
            nn.Linear(hidden, hidden),
            nn.Tanh(),
            nn.Linear(hidden, 1),
        )

    def forward(self, state: torch.Tensor) -> torch.Tensor:
        return self.net(state).squeeze(-1)


@dataclass
class MFCTransition:
    state: np.ndarray
    features: np.ndarray
    latent: np.ndarray
    log_prob: float
    value: float
    reward: float


class MFCDIPolicy:
    def __init__(self, env: JointMAPPOEdgeEnv, args: argparse.Namespace) -> None:
        self.env = env
        self.args = args
        self.device = torch.device(args.device or ("cuda" if torch.cuda.is_available() else "cpu"))
        self.rng = np.random.default_rng(args.seed * 7919 + 17)
        self.d = int(args.mfc_d)
        if not 1 < self.d <= env.cfg.n_edges:
            raise ValueError("mfc_d must be in [2, n_edges]")
        self.bins = int(args.mfc_queue_bins)
        # Per-client feature: stale histogram + d queue states + d comm/service
        # costs + request intensity + global arrival intensity.
        feature_dim = self.bins + 2 * self.d + 2
        state_dim = self.bins + 1
        torch.manual_seed(args.seed)
        self.actor = MFCActor(feature_dim, self.d, args.mfc_hidden).to(self.device)
        self.critic = MFCCritic(state_dim, args.mfc_hidden).to(self.device)
        self.optimizer = torch.optim.Adam(
            list(self.actor.parameters()) + list(self.critic.parameters()),
            lr=args.mfc_learning_rate,
        )
        self.rollout: list[MFCTransition] = []

    def _histogram(self, wait_norm: np.ndarray) -> np.ndarray:
        indices = np.minimum((np.clip(wait_norm, 0.0, 1.0) * self.bins).astype(int), self.bins - 1)
        hist = np.bincount(indices, minlength=self.bins).astype(np.float32)
        return hist / max(float(hist.sum()), 1.0)

    def _state_and_features(self) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        feedback = self.env.feedback_buffer.get(self.env.feedback_delay)
        histogram = self._histogram(feedback.wait_norm)
        arrival = float(np.sum(self.env.requests)) / max(
            float(self.env.cfg.n_users * self.env.cfg.max_requests_per_user), 1.0
        )
        state = np.concatenate([histogram, np.asarray([arrival], dtype=np.float32)])
        candidates = np.stack(
            [self.rng.choice(self.env.cfg.n_edges, size=self.d, replace=False) for _ in range(self.env.cfg.n_users)]
        )
        locations = self.env._locations()
        features: list[np.ndarray] = []
        for user, edges in enumerate(candidates):
            queue_state = feedback.wait_norm[edges].astype(np.float32)
            completion = np.asarray(
                [
                    self.env._transmission_delay_s(locations[user], int(edge))
                    + self.env.cfg.task_compute_mb / max(float(self.env.edge_capacities_mb_s[edge]), EPS)
                    + float(feedback.wait_s[edge])
                    for edge in edges
                ],
                dtype=np.float32,
            )
            completion /= max(float(self.args.mfc_latency_norm), EPS)
            request = float(self.env.requests[user]) / max(float(self.env.cfg.max_requests_per_user), 1.0)
            features.append(
                np.concatenate(
                    [histogram, queue_state, completion, np.asarray([request, arrival], dtype=np.float32)]
                )
            )
        return state.astype(np.float32), np.asarray(features, dtype=np.float32), candidates

    def act(self, deterministic: bool) -> tuple[np.ndarray, np.ndarray, np.ndarray, float, float]:
        state, features, candidates = self._state_and_features()
        feature_t = torch.as_tensor(features, dtype=torch.float32, device=self.device)
        state_t = torch.as_tensor(state[None], dtype=torch.float32, device=self.device)
        with torch.no_grad():
            dist = self.actor.distribution(feature_t)
            latent = dist.mean if deterministic else dist.sample()
            log_prob = float(dist.log_prob(latent).sum().cpu())
            value = float(self.critic(state_t).item())
            local_weights = torch.softmax(latent, dim=-1).cpu().numpy()
        portfolios = np.zeros((self.env.cfg.n_users, self.env.cfg.n_edges), dtype=np.float32)
        for user, edges in enumerate(candidates):
            portfolios[user, edges] = local_weights[user]
        return portfolios, state, features, latent.cpu().numpy().astype(np.float32), log_prob, value

    def add(self, state: np.ndarray, features: np.ndarray, latent: np.ndarray, log_prob: float, value: float, reward: float) -> None:
        self.rollout.append(MFCTransition(state, features, latent, log_prob, value, reward))

    def maybe_update(self, force: bool = False) -> dict[str, float]:
        if len(self.rollout) < self.args.mfc_rollout and not force:
            return {}
        if not self.rollout:
            return {}
        rewards = np.asarray([x.reward for x in self.rollout], dtype=np.float32)
        values = np.asarray([x.value for x in self.rollout], dtype=np.float32)
        advantages = np.zeros_like(rewards)
        gae = 0.0
        for index in reversed(range(len(rewards))):
            next_value = values[index + 1] if index + 1 < len(values) else 0.0
            delta = rewards[index] + self.args.gamma * next_value - values[index]
            gae = delta + self.args.gamma * self.args.gae_lambda * gae
            advantages[index] = gae
        returns = advantages + values
        advantages = (advantages - advantages.mean()) / (advantages.std() + 1e-8)

        states = torch.as_tensor(np.stack([x.state for x in self.rollout]), dtype=torch.float32, device=self.device)
        features = torch.as_tensor(np.stack([x.features for x in self.rollout]), dtype=torch.float32, device=self.device)
        latent = torch.as_tensor(np.stack([x.latent for x in self.rollout]), dtype=torch.float32, device=self.device)
        old_logp = torch.as_tensor([x.log_prob for x in self.rollout], dtype=torch.float32, device=self.device)
        adv = torch.as_tensor(advantages, dtype=torch.float32, device=self.device)
        ret = torch.as_tensor(returns, dtype=torch.float32, device=self.device)
        actor_loss_value = critic_loss_value = entropy_value = 0.0
        for _ in range(self.args.mfc_update_epochs):
            dist = self.actor.distribution(features.flatten(0, 1))
            new_logp = dist.log_prob(latent.flatten(0, 1)).sum(dim=-1).reshape(len(self.rollout), -1).sum(dim=-1)
            ratio = torch.exp(new_logp - old_logp)
            clipped = torch.clamp(ratio, 1.0 - self.args.mfc_clip, 1.0 + self.args.mfc_clip)
            actor_loss = -torch.minimum(ratio * adv, clipped * adv).mean()
            values_t = self.critic(states)
            critic_loss = torch.mean((values_t - ret) ** 2)
            entropy = dist.entropy().sum(dim=-1).mean()
            loss = actor_loss + self.args.mfc_value_coef * critic_loss - self.args.mfc_entropy_coef * entropy
            self.optimizer.zero_grad(set_to_none=True)
            loss.backward()
            nn.utils.clip_grad_norm_(list(self.actor.parameters()) + list(self.critic.parameters()), 0.5)
            self.optimizer.step()
            actor_loss_value = float(actor_loss.detach().cpu())
            critic_loss_value = float(critic_loss.detach().cpu())
            entropy_value = float(entropy.detach().cpu())
        self.rollout.clear()
        return {"actor_loss": actor_loss_value, "critic_loss": critic_loss_value, "entropy": entropy_value}


def _run_jseq(args: argparse.Namespace) -> dict[str, object]:
    env, system, _ = _build_environment(args, args.seed + 10_000)
    policy = JSEQPolicy(env, args.jseq_temperature)
    results: list[SlotResult] = []
    latency_rows: list[dict[str, object]] = []
    learning_rows: list[dict[str, object]] = []
    for slot in range(1, args.test_steps + 1):
        started = perf_counter()
        result = env.joint_step(policy.portfolios(), decision_latency_s=perf_counter() - started)
        policy.observe(result)
        results.append(result)
        _record_latencies(latency_rows, result, "test", slot)
        if slot == 1 or slot % args.log_interval == 0 or slot == args.test_steps:
            row: dict[str, object] = {"slot": slot, "step": slot * system.n_users}
            row.update(slot_metrics(result))
            learning_rows.append(row)
    summary, _ = finalize_evaluation(env, results, system)
    summary.update(phase_diagnostics(results, system))
    summary.update(
        {
            "method": JSEQ_A,
            "source_paper_doi": "10.1287/moor.2020.1056",
            "reproduction_level": "mechanism-faithful environment adaptation",
            "architecture": "delayed queue estimator plus completion-cost soft routing",
            "uses_fresh_queue": False,
            "dataset": args.dataset,
            "users": args.users,
            "train_steps": 0,
            "test_steps": args.test_steps,
            "feedback_delay": args.feedback_delay,
            "broadcast_period": args.broadcast_period,
        }
    )
    _save_outputs(
        args, JSEQ_A, learning_rows, latency_rows, summary,
        {"estimator": "delayed broadcast queue + known own arrival/service history", "temperature": args.jseq_temperature},
    )
    return summary


def _run_mfc(args: argparse.Namespace) -> dict[str, object]:
    train_env, system, _ = _build_environment(args, args.seed)
    policy = MFCDIPolicy(train_env, args)
    learning_rows: list[dict[str, object]] = []
    latency_rows: list[dict[str, object]] = []
    started_all = perf_counter()
    last_stats: dict[str, float] = {}
    for slot in range(1, args.train_steps + 1):
        started = perf_counter()
        portfolios, state, features, latent, logp, value = policy.act(deterministic=False)
        result = train_env.joint_step(portfolios, decision_latency_s=perf_counter() - started)
        policy.add(state, features, latent, logp, value, -result.system_average_latency / args.mfc_latency_norm)
        last_stats = policy.maybe_update()
        _record_latencies(latency_rows, result, "train", slot)
        if slot == 1 or slot % args.log_interval == 0 or slot == args.train_steps:
            row: dict[str, object] = {
                "slot": slot,
                "step": slot * system.n_users,
                "elapsed_s": perf_counter() - started_all,
                **last_stats,
            }
            row.update(slot_metrics(result))
            learning_rows.append(row)
    policy.maybe_update(force=True)

    # Keep the original training seed on the environment arguments so the
    # shared builder can unambiguously classify seed+10000 as the held-out
    # test role.  The policy gets its own evaluation seed copy.
    eval_args = argparse.Namespace(**vars(args))
    eval_args.seed = args.seed + 10_000
    eval_env, _, _ = _build_environment(args, args.seed + 10_000)
    eval_policy = MFCDIPolicy(eval_env, eval_args)
    eval_policy.actor.load_state_dict(policy.actor.state_dict())
    eval_policy.critic.load_state_dict(policy.critic.state_dict())
    results: list[SlotResult] = []
    for slot in range(1, args.test_steps + 1):
        started = perf_counter()
        portfolios, *_ = eval_policy.act(deterministic=True)
        result = eval_env.joint_step(portfolios, decision_latency_s=perf_counter() - started)
        results.append(result)
        _record_latencies(latency_rows, result, "test", slot)
    summary, _ = finalize_evaluation(eval_env, results, system)
    summary.update(phase_diagnostics(results, system))
    if train_env.canonical_schedule is not None:
        summary["train_split_id"] = train_env.canonical_schedule.schedule_id
        summary["train_schedule_sha256"] = train_env.canonical_schedule.content_sha256
    summary.update(
        {
            "method": MFC_DI_A,
            "source_paper_doi": "10.1145/3545008.3545025",
            "source_code": "third_party/mfc_large_queueing_systems",
            "reproduction_level": "algorithm-structure environment adaptation",
            "architecture": "stale queue-state distribution + random power-of-d + shared PPO",
            "uses_fresh_queue": False,
            "dataset": args.dataset,
            "users": args.users,
            "train_steps": args.train_steps,
            "test_steps": args.test_steps,
            "feedback_delay": args.feedback_delay,
            "broadcast_period": args.broadcast_period,
        }
    )
    _save_outputs(
        args, MFC_DI_A, learning_rows, latency_rows, summary,
        {
            "retained": ["empirical queue-state distribution", "random d-choice", "PPO policy gradient"],
            "adapted": ["mobility communication cost", "MEC task requests", "finite N/M simulator"],
            "d": args.mfc_d,
            "queue_bins": args.mfc_queue_bins,
        },
    )
    output = Path(args.output_dir) / args.dataset / f"{args.users}u" / args.distribution
    torch.save(
        {"actor": policy.actor.state_dict(), "critic": policy.critic.state_dict(), "args": vars(args)},
        output / f"checkpoint_{MFC_DI_A}.pt",
    )
    checkpoint_path = output / f"checkpoint_{MFC_DI_A}.pt"
    write_run_manifest(
        output_dir=output,
        method=MFC_DI_A,
        args=args,
        summary=summary,
        config_path=output / f"config_{MFC_DI_A}.json",
        checkpoint_path=checkpoint_path,
    )
    return summary


def train_once(args: argparse.Namespace) -> dict[str, object]:
    torch.set_num_threads(args.torch_threads)
    if args.method == JSEQ_A:
        return _run_jseq(args)
    if args.method == MFC_DI_A:
        return _run_mfc(args)
    raise ValueError(args.method)


