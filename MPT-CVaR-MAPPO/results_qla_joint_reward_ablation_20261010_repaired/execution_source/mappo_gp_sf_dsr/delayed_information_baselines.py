"""Paper-grounded delayed-information load-balancing baselines.

The module adds two baselines without changing QLA-MAPPO:

* ``JSEQ-A`` adapts Atar--Lipshutz join-the-shortest-estimated-queue.  It
  reconstructs the delayed queue from the broadcast wait summary and advances
  that state with only the controller's own recorded arrivals and known service
  rates.  It never reads the environment's current queue.
* ``MFC-DI-A`` ports the algorithmic structure of Tahir--Cui--Koeppl: a stale
  empirical queue-state distribution, random power-of-d candidates, and a PPO
  policy shared across clients.  Mobility/request features are environment
  adapters; the original continuous-time queue simulator is not reproduced.

Both methods write the same summary/latency artifacts as the existing adapted
MEC baselines so that they can enter the common-grid audit and figure pipeline.
"""

